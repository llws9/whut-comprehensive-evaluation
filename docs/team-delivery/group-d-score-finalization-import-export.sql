-- 负责表：
--   final_record
--   final_component_score
--
-- 说明：
-- 1. 一期采用同步导入/同步导出，不新增 import_job/export_job 表。
-- 2. 本脚本中的 `physical_total` 沿用冻结稿字段命名；业务语义对应“体育与美育”总分。

SET NAMES utf8mb4;

DROP TABLE IF EXISTS `final_component_score`;
DROP TABLE IF EXISTS `final_record`;

CREATE TABLE `final_record` (
  `id` BIGINT NOT NULL,
  `student_user_id` BIGINT NOT NULL,
  `academic_year` VARCHAR(32) NOT NULL,
  `status` VARCHAR(32) NOT NULL,
  `moral_total` DECIMAL(10,2) NOT NULL,
  `intellectual_total` DECIMAL(10,2) NOT NULL,
  `physical_total` DECIMAL(10,2) NOT NULL,
  `labor_total` DECIMAL(10,2) NOT NULL,
  `grand_total` DECIMAL(10,2) NOT NULL,
  `submitted_at` DATETIME DEFAULT NULL,
  `confirmed_at` DATETIME DEFAULT NULL,
  `version` BIGINT NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_final_record_student_user_id` (`student_user_id`),
  KEY `idx_final_record_academic_year` (`academic_year`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='学生学年最终成绩表头';

CREATE TABLE `final_component_score` (
  `id` BIGINT NOT NULL,
  `final_record_id` BIGINT NOT NULL,
  `category_code` VARCHAR(64) NOT NULL,
  `item_code` VARCHAR(64) NOT NULL,
  `score_value` DECIMAL(10,2) NOT NULL,
  `display_text` VARCHAR(1000) DEFAULT NULL,
  `source_type` VARCHAR(32) NOT NULL,
  `source_ref_id` VARCHAR(64) DEFAULT NULL,
  `created_at` DATETIME NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_final_component_score_final_record_id` (`final_record_id`),
  KEY `idx_final_component_score_category_code` (`category_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='冻结后的分项明细';

